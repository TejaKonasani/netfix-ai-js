// Vercel build step — injects the backend API URL into the static site.
// The value comes from the VERCEL_API_URL environment variable set on the
// frontend project in Vercel (e.g. https://netfix-ai-backend.vercel.app/api/v1).
// For local development the default (http://localhost:5000/api/v1) is kept.
const fs = require("fs");
const path = require("path");

const apiUrl = (process.env.VERCEL_API_URL || "http://localhost:5000/api/v1").replace(/\/$/, "");

const config = `// AUTO-GENERATED by build.js at deploy time — do not edit by hand.
window.NETFIX_CONFIG = { API_URL: ${JSON.stringify(apiUrl)} };
`;

const jsDir = path.join(__dirname, "js");
fs.mkdirSync(jsDir, { recursive: true });
fs.writeFileSync(path.join(jsDir, "config.js"), config);
console.log("[build] injected API URL:", apiUrl);